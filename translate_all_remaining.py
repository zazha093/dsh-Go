def convert_plural_to_thai(text):
    """Convert ICU plural format to Thai (only 'other' form)"""
    # Pattern: {var, plural, =1{...} one{...} other{...}}
    # We want to extract only the 'other' case
    pattern = r'\{([^}]+)\}'
    
    def replace_plural(match):
        content = match.group(1)
        # Check if it's a plural/select format
        if ',' in content:
            parts = content.split(',', 1)
            var_name = parts[0].strip()
            rest = parts[1].strip()
            if rest.startswith('plural') or rest.startswith('select'):
                # Extract the 'other' case
                # Format: plural, =1{...} other{...} or select, option1{...} other{...}
                cases = rest.split('}')[0] if '}' in rest else rest
                # Find other{...}
                other_match = re.search(r'other\{([^}]*)\}', rest)
                if other_match:
                    return other_match.group(1)
                # If no 'other', try to get the last case
                case_matches = re.findall(r'\w+\{([^}]*)\}', rest)
                if case_matches:
                    return case_matches[-1]
        return match.group(0)
    
    return re.sub(pattern, replace_plural, text)

def translate_text(text, key=''):
    """Translate text to Thai, keeping technical terms"""
    if not text or not text.strip():
        return text
    
    # Handle plural/select ICU format - convert to Thai 'other' form
    if '{' in text and ('plural' in text or 'select' in text):
        return convert_plural_to_thai(text)
    
    # Check if text is a simple key that should be translated
    # If it contains placeholders, keep structure but translate words
    if '{' in text and '}' in text:
        # Has placeholders - translate the non-placeholder parts
        # This is complex, for now keep technical terms
        words = text.split()
        # Check if mostly technical
        tech_count = sum(1 for w in words if w.strip('{}.,!?') in TECHNICAL_TERMS)
        if tech_count > len(words) * 0.5:
            return text  # Mostly technical, keep as is
    
    # Direct translation lookup
    if text in UI_TRANSLATIONS:
        return UI_TRANSLATIONS[text]
    
    # Check for partial matches (start of string)
    for eng, thai in UI_TRANSLATIONS.items():
        if text.startswith(eng + ' ') or text.startswith(eng + '\n') or text == eng:
            return text.replace(eng, thai, 1)
        if text.endswith(' ' + eng) or text.endswith('\n' + eng) or text == eng:
            return text.replace(eng, thai)
    
    # For technical terms, keep as is
    words = text.split()
    if words and all(w.strip('{}.,!?:;') in TECHNICAL_TERMS for w in words if w.strip('{}.,!?:;')):
        return text
    
    # Default: return original (will be manually reviewed)
    return text

def load_arb(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f, object_pairs_hook=lambda pairs: dict(pairs))

def save_arb(data, path):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

def translate_part(area):
    """Translate a single part from English to Thai"""
    en_path = f'app/lib/l10n/parts/{area}_en.arb'
    zh_path = f'app/lib/l10n/parts/{area}_zh.arb'
    th_path = f'app/lib/l10n/parts/{area}_th.arb'
    
    if not os.path.exists(en_path):
        print(f"English file not found: {en_path}")
        return False
    
    # Check if Thai already exists
    if os.path.exists(th_path):
        print(f"Thai file already exists: {th_path}, skipping")
        return True
    
    en_data = load_arb(en_path)
    zh_data = load_arb(zh_path) if os.path.exists(zh_path) else {}
    
    th_data = {'@@locale': 'th'}
    
    for key, value in en_data.items():
        if key.startswith('@'):
            # Metadata - copy from Chinese or English
            th_data[key] = zh_data.get(key, value)
        else:
            # Translate the value
            th_data[key] = translate_text(value, key)
    
    save_arb(th_data, th_path)
    key_count = len([k for k in th_data if not k.startswith('@')])
    print(f"Created {th_path} with {key_count} keys")
    return True

